-- 17 · Chiến dịch vận chuyển (Thiết bị cơ giới › Kế hoạch & báo cáo › Chiến dịch)
-- Một chiến dịch gồm thông tin chung, cấu hình ca / giờ nghỉ và một hoặc nhiều TUYẾN chạy cùng lúc
-- (lưu dạng jsonb trong cột cau_hinh, tuyen; web tự tính số xe, số điểm, giãn cách, biểu đồ chạy xe).
-- Bảng chien_dich_thuc_te: khối lượng thực tế theo tuyến × ngày × ca để so với kế hoạch.
-- Chạy SAU SQL 16 (dùng hàm co_nhom). Chạy được nhiều lần. Chưa chạy thì tab Chiến dịch báo cần chạy SQL 17.

create table if not exists public.chien_dich (
  id          bigint generated by default as identity primary key,
  ten         text not null,
  bat_dau     timestamptz not null,
  trang_thai  text not null default 'ke_hoach' check (trang_thai in ('ke_hoach', 'dang_chay', 'xong', 'huy')),
  cau_hinh    jsonb not null default '{}'::jsonb,   -- ca làm việc, giờ nghỉ
  tuyen       jsonb not null default '[]'::jsonb,   -- danh sách tuyến: khối lượng, quãng đường, tốc độ, năng suất xếp / vun, ưu tiên…
  ghi_chu     text,
  nguoi_tao   uuid default auth.uid(),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists chien_dich_bat_dau_idx on public.chien_dich (bat_dau desc);

create table if not exists public.chien_dich_thuc_te (
  id            bigint generated by default as identity primary key,
  chien_dich_id bigint not null references public.chien_dich(id) on delete cascade,
  tuyen_id      text not null,
  ngay          date not null,               -- ngày của ca (CA 2 qua nửa đêm vẫn tính ngày bắt đầu ca)
  ca            int  not null check (ca >= 1),
  khoi_luong    numeric check (khoi_luong >= 0),
  so_chuyen     int check (so_chuyen >= 0),
  so_xe         int check (so_xe >= 0),
  ghi_chu       text,
  updated_at    timestamptz not null default now(),
  unique (chien_dich_id, tuyen_id, ngay, ca)
);
create index if not exists cdtt_cd_idx on public.chien_dich_thuc_te (chien_dich_id);

-- Quyền: mọi tài khoản xem; nhập liệu / quản trị (vai trò Thiết bị cơ giới) và nhóm van_tai được ghi
alter table public.chien_dich enable row level security;
alter table public.chien_dich_thuc_te enable row level security;
drop policy if exists cd_doc on public.chien_dich;
drop policy if exists cd_ghi on public.chien_dich;
drop policy if exists cdtt_doc on public.chien_dich_thuc_te;
drop policy if exists cdtt_ghi on public.chien_dich_thuc_te;
create policy cd_doc on public.chien_dich for select using (public.co_vai_tro(array['xem','nhap','quan_tri']));
create policy cd_ghi on public.chien_dich for all
  using (public.co_vai_tro(array['nhap','quan_tri']) or public.co_nhom(array['van_tai']))
  with check (public.co_vai_tro(array['nhap','quan_tri']) or public.co_nhom(array['van_tai']));
create policy cdtt_doc on public.chien_dich_thuc_te for select using (public.co_vai_tro(array['xem','nhap','quan_tri']));
create policy cdtt_ghi on public.chien_dich_thuc_te for all
  using (public.co_vai_tro(array['nhap','quan_tri']) or public.co_nhom(array['van_tai']))
  with check (public.co_vai_tro(array['nhap','quan_tri']) or public.co_nhom(array['van_tai']));

drop trigger if exists chien_dich_updated on public.chien_dich;
create trigger chien_dich_updated before update on public.chien_dich for each row execute function public.set_updated_at();
drop trigger if exists cdtt_updated on public.chien_dich_thuc_te;
create trigger cdtt_updated before update on public.chien_dich_thuc_te for each row execute function public.set_updated_at();

